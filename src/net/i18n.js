/** t('net.key', params) with English fallback and {placeholders}. */
export function makeT(game) {
  let registered = false;
  return (key, params) => {
    const i18n = game.i18n;
    if (i18n?.register && !registered) { try { i18n.register('net', NET_STRINGS); } catch { /* older i18n */ } registered = true; }
    const full = `net.${key}`;
    const s = i18n?.t?.(full, params);
    if (s && s !== full) return s;
    const raw = NET_STRINGS.en[key] ?? key;
    return params ? raw.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m)) : raw;
  };
}

export const NET_KEYS = Object.keys(NET_STRINGS.en).map((k) => `net.${k}`);
